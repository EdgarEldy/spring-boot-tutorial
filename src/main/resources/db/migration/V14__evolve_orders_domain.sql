-- Evolve the orders domain for e-commerce: multi-line items, status lifecycle,
-- BigDecimal amounts and unique order numbers. customer_id/product_id are made
-- nullable so that future checkout-created orders can reference AppUser instead.

-- 1. Add e-commerce columns to orders
ALTER TABLE orders
    ADD COLUMN order_number VARCHAR(50) UNIQUE,
    ADD COLUMN status       VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    ADD COLUMN total_amount NUMERIC(12,2);

-- 2. Make customer_id and product_id nullable for forward compatibility
--    (checkout orders will own the customer link via user_id, added in a later migration)
ALTER TABLE orders ALTER COLUMN customer_id DROP NOT NULL;
ALTER TABLE orders ALTER COLUMN product_id  DROP NOT NULL;

-- 3. Create order_items table (product snapshot: name and price at order time)
CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT NOT NULL REFERENCES orders(id),
    product_id   BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name VARCHAR(255) NOT NULL,
    unit_price   NUMERIC(12,2) NOT NULL,
    quantity     INT NOT NULL CHECK (quantity > 0),
    subtotal     NUMERIC(12,2) NOT NULL
);

CREATE INDEX idx_order_items_order_id ON order_items(order_id);

-- 4. Migrate historical orders: one OrderItem per existing order using the
--    current NUMERIC(12,2) product price (more accurate than the DOUBLE total column)
INSERT INTO order_items (order_id, product_id, product_name, unit_price, quantity, subtotal)
SELECT
    o.id,
    o.product_id,
    p.product_name,
    p.unit_price,
    o.quantity,
    ROUND(CAST(o.quantity AS NUMERIC) * p.unit_price, 2)
FROM orders o
JOIN products p ON p.id = o.product_id;

-- 5. Backfill total_amount from quantity * current product price
UPDATE orders o
SET total_amount = (
    SELECT ROUND(CAST(o.quantity AS NUMERIC) * p.unit_price, 2)
    FROM products p WHERE p.id = o.product_id
)
WHERE o.product_id IS NOT NULL;

-- 6. Backfill order_number for historical orders
UPDATE orders SET order_number = 'ORD-HIST-' || LPAD(id::TEXT, 6, '0');
