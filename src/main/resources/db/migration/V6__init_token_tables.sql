-- Token tables for account activation, password reset, and JWT revocation.
-- activation_tokens: single-use, 24-hour lifetime, marked as used via validated_at.
-- password_reset_tokens: single-use, 1-hour lifetime, deleted on consumption.
-- blacklisted_tokens: stores revoked JWTs by jti until their natural expiry.

CREATE TABLE activation_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES app_users (id),
    token        VARCHAR(255) NOT NULL UNIQUE,
    created_at   TIMESTAMP NOT NULL,
    expires_at   TIMESTAMP,
    validated_at TIMESTAMP
);

CREATE INDEX idx_activation_tokens_user_id ON activation_tokens (user_id);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_users (id),
    token       VARCHAR(255) NOT NULL UNIQUE,
    type        VARCHAR(255) NOT NULL,
    expiry_date TIMESTAMP NOT NULL
);

CREATE INDEX idx_password_reset_tokens_user_id ON password_reset_tokens (user_id);

CREATE TABLE blacklisted_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES app_users (id),
    token          VARCHAR(768) NOT NULL,
    jti            VARCHAR(255) NOT NULL UNIQUE,
    blacklisted_at TIMESTAMP,
    created_at     TIMESTAMP NOT NULL,
    expires_at     TIMESTAMP
);

CREATE INDEX idx_blacklisted_tokens_user_id ON blacklisted_tokens (user_id);
