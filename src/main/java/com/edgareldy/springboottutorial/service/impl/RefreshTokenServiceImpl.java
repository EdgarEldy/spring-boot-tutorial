package com.edgareldy.springboottutorial.service.impl;

import com.edgareldy.springboottutorial.entity.token.RefreshToken;
import com.edgareldy.springboottutorial.entity.user.AppUser;
import com.edgareldy.springboottutorial.exception.InvalidTokenException;
import com.edgareldy.springboottutorial.exception.TokenExpiredException;
import com.edgareldy.springboottutorial.repository.RefreshTokenRepository;
import com.edgareldy.springboottutorial.security.JwtProperties;
import com.edgareldy.springboottutorial.security.JwtService;
import com.edgareldy.springboottutorial.service.RefreshTokenService;
import java.time.Instant;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Default {@link RefreshTokenService} implementation backed by
 * {@link RefreshTokenRepository}. Tokens are opaque strings generated by
 * {@link JwtService#generateRefreshToken} and stored in the database; each
 * validate call checks expiry against the database row, not the JWT
 * signature, so a revoked token is detected even if the JWT has not expired.
 * <p>
 * Created edgar.muhamyangabo on 11/9/26
 * Author : edgar.muhamyangabo
 * Date : 11/9/26
 * Project : spring-boot-tutorial
 */
@Service
@RequiredArgsConstructor
public class RefreshTokenServiceImpl implements RefreshTokenService {

    private final RefreshTokenRepository refreshTokenRepository;
    private final JwtService jwtService;
    private final JwtProperties jwtProperties;

    @Override
    @Transactional
    public RefreshToken generate(AppUser user) {
        refreshTokenRepository.deleteByUser(user);
        Instant now = Instant.now();
        String rawToken = jwtService.generateRefreshToken(user.getUsername());
        RefreshToken refreshToken = RefreshToken.builder()
                .user(user)
                .token(rawToken)
                .createdAt(now)
                .expiresAt(now.plusMillis(jwtProperties.refreshExpirationMs()))
                .build();
        return refreshTokenRepository.save(refreshToken);
    }

    @Override
    @Transactional(readOnly = true)
    public RefreshToken validate(String rawToken) {
        RefreshToken refreshToken = refreshTokenRepository.findByToken(rawToken)
                .orElseThrow(() -> new InvalidTokenException("Invalid refresh token"));
        if (refreshToken.getExpiresAt().isBefore(Instant.now())) {
            throw new TokenExpiredException("Refresh token has expired");
        }
        return refreshToken;
    }

    @Override
    @Transactional
    public void deleteByUser(AppUser user) {
        refreshTokenRepository.deleteByUser(user);
    }
}
